STATES=("FD","plus","minus")
ZS=(.945,.95,.955)
FIELDS=("Pcb","theta","dcb")

def ck(a,s):
    if not a:raise RuntimeError("E17B_INDEPENDENT_FAIL_CLOSED: "+s)
def sha(x):return hashlib.sha256(x).hexdigest()
def blob(x):return hashlib.sha1(b"blob "+str(len(x)).encode()+b"\0"+x).hexdigest()
def scaled(a,b,floor):return abs(a-b)/max(abs(a),abs(b),floor)
def interp(ks,arr,x):
    i=bisect.bisect_right(ks,x)
    ck(i>0 and i<len(ks),"native CLASS leg outside measured k grid")
    lo=ks[i-1];hi=ks[i]
    ck(hi>lo,"native CLASS k monotonicity lost")
    return arr[i-1]+(x-lo)/(hi-lo)*(arr[i]-arr[i-1])
def write_new(path,obj):
    raw=(json.dumps(obj,indent=2,allow_nan=False)+"\n").encode()
    path.parent.mkdir(parents=True,exist_ok=True)
    if path.exists():ck(path.read_bytes()==raw,"independent cert output collision")
    else:
        with tempfile.NamedTemporaryFile(dir=path.parent,prefix=".e17b_ind_",delete=False) as f:
            t=Path(f.name);f.write(raw);f.flush();os.fsync(f.fileno())
        try:os.link(t,path)
        finally:t.unlink(missing_ok=True)
    print("E17B_INDEPENDENT_CERTIFICATE",path,"SHA256",sha(raw),flush=True)

