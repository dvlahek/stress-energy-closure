        ck(sha(oldpath.read_bytes())==pins["E17A_original_per_state_sha256"][st],
           "E17A original state SHA changed")
        old=json.loads(oldpath.read_bytes())
        rows=old["rows_original_576_geometry_three_z_two_legs"]
        ck(len(rows)==576,"original frozen 576 triangles changed")
        legs=[row["k"+str(i)+"_h_Mpc"] for row in rows for i in (1,2)]
        baseline={str(z):{f:[] for f in FIELDS} for z in ZS}
        for z in ZS:
            for row in rows:
                for i in (1,2):
                    r=row["z_nodes"][str(z)]["leg"+str(i)]
                    baseline[str(z)]["Pcb"].append(r["P_cb_CLASS_Mpc3"])
                    baseline[str(z)]["theta"].append(r["theta_rel_DIRECT_vTk_per_R_Mpc_inv"])
                    baseline[str(z)]["dcb"].append(r["delta_cb_Newtonian_per_R"])
                    qa["original_baseline_leg_z_field_comparisons"]+=3
        data=a["native_CLASS_evaluations_by_fixed_tier"]
